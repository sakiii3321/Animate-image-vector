const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'../..'),publicDir=path.join(root,'outputs/illustration-blind-review-round2');
const M=require(path.join(publicDir,'review-model.js'));
const sandbox={window:{}};vm.runInNewContext(fs.readFileSync(path.join(publicDir,'data.js'),'utf8'),sandbox);
const data=JSON.parse(JSON.stringify(sandbox.window.REVIEW_DATA)),model=M.create(data);
assert.deepEqual(M.progress(model),{complete:0,total:48});
for(const [key] of M.dimensions)model.rows[0][key]=4;
model.rows[0].notes='眼部, "缺失"\n细线连续';model.reviewer='评分人';
assert.deepEqual(M.progress(model),{complete:1,total:48});
assert.deepEqual(M.validate(data,JSON.parse(JSON.stringify(model))),model);
assert.throws(()=>M.validate(data,{...model,experiment_id:'illustration-daca0863fa'}),/不属于/);
assert.throws(()=>M.validate(data,{...model,rows:[{...model.rows[0],overall:6}]}),/1～5/);
assert.throws(()=>M.validate(data,{...model,rows:[{...model.rows[0],overall:'4'}]}),/1～5/);
assert.throws(()=>M.validate(data,{...model,rows:[model.rows[0],model.rows[0]]}),/重复/);
assert.throws(()=>M.validate(data,{...model,rows:[{...model.rows[0],candidate:'Z'}]}),/编号/);
const partial=M.validate(data,{...model,rows:[model.rows[0]]});
assert.deepEqual(M.progress(partial),{complete:1,total:48});assert.equal(partial.rows[1].overall,null);
assert.ok(M.csv(model).includes('"眼部, ""缺失""\n细线连续"'));
assert.ok(!JSON.stringify(model).includes('method'));
console.log('PASS: 48 entries, partial ratings, JSON round-trip, old-batch rejection, score bounds, duplicates, CSV escaping, anonymous export.');
